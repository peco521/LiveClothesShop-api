-- FashionStore / Examen Parcial 2 - ICONIX
-- Nombres conservados del primer parcial para facilitar la evolucion FastAPI.
-- Restricciones multitenant: idEmp y FK compuestas en toda entidad comercial.
-- PK originales son globales (secuencias/UUID globales), para compatibilidad con la API.
BEGIN;

-- =================== PLATAFORMA SAAS ===================
CREATE TABLE funcionalidad_saas (
  codigo varchar(30) PRIMARY KEY,
  descripcion varchar(100) NOT NULL
);
CREATE TABLE plan (
  idPlan smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(30) NOT NULL UNIQUE,
  maxSucursales smallint NOT NULL CHECK (maxSucursales > 0),
  estado varchar(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo'))
);
CREATE TABLE plan_funcionalidad (
  idPlan smallint NOT NULL REFERENCES plan(idPlan) ON UPDATE CASCADE ON DELETE CASCADE,
  codigo varchar(30) NOT NULL REFERENCES funcionalidad_saas(codigo) ON UPDATE CASCADE ON DELETE CASCADE,
  PRIMARY KEY (idPlan,codigo)
);
CREATE TABLE empresa (
  idEmp integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE CHECK (codigo ~ '^[a-z0-9-]+$'),
  nombre varchar(100) NOT NULL,
  nit varchar(30),
  estado varchar(20) NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa','suspendida','inactiva')),
  diasPlazoCambio smallint NOT NULL DEFAULT 15 CHECK (diasPlazoCambio >= 0),
  diasPlazoDevolucion smallint NOT NULL DEFAULT 7 CHECK (diasPlazoDevolucion >= 0),
  porcentajeDevolucion numeric(5,2) NOT NULL DEFAULT 100 CHECK (porcentajeDevolucion > 0 AND porcentajeDevolucion <= 100),
  condicionesDevolucion text,
  horasMargenReserva smallint NOT NULL DEFAULT 3 CHECK (horasMargenReserva >= 0),
  creadaEn timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE suscripcion (
  idSusc integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idEmp integer NOT NULL REFERENCES empresa(idEmp) ON DELETE RESTRICT,
  idPlan smallint NOT NULL REFERENCES plan(idPlan) ON DELETE RESTRICT,
  fechaInicio date NOT NULL,
  fechaVencimiento date NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa','vencida','suspendida','cancelada','reemplazada')),
  creadaEn timestamptz NOT NULL DEFAULT now(),
  CHECK (fechaVencimiento >= fechaInicio)
);
CREATE UNIQUE INDEX uq_suscripcion_activa ON suscripcion(idEmp) WHERE estado = 'activa';
CREATE INDEX ix_suscripcion_emp_vigencia ON suscripcion(idEmp,fechaVencimiento);

-- =================== SEGURIDAD Y ACCESO ===================
-- Rol y usuario con idEmp NULL reservados exclusivamente para administrador SaaS.
CREATE TABLE rol (
  nro varchar(15) PRIMARY KEY,
  descripcion varchar(50) NOT NULL,
  idEmp integer REFERENCES empresa(idEmp),
  UNIQUE (idEmp,nro)
);
INSERT INTO rol(nro,descripcion,idEmp) VALUES ('SAAS-ADMIN','Administrador de la plataforma SaaS',NULL);
CREATE TABLE funcion (
  id varchar(15) PRIMARY KEY,
  descripcion varchar(50)
);
CREATE TABLE rol_funcion (
  nroRol varchar(15) NOT NULL,
  idFun varchar(15) NOT NULL REFERENCES funcion(id) ON UPDATE CASCADE ON DELETE CASCADE,
  descripcion varchar(100) NOT NULL,
  idEmp integer REFERENCES empresa(idEmp),
  PRIMARY KEY (nroRol,idFun),
  FOREIGN KEY (idEmp,nroRol) REFERENCES rol(idEmp,nro) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE usuario (
  idUsuario varchar PRIMARY KEY,
  ci varchar NOT NULL,
  nombre varchar(100) NOT NULL,
  apellidoPat varchar(50) NOT NULL,
  apellidoMat varchar(50) NOT NULL,
  sexo char(1) NOT NULL CHECK (sexo IN ('M','F')),
  correo varchar(100) NOT NULL,
  telefono varchar(20) NOT NULL,
  direccion varchar(150) NOT NULL,
  contrasena text NOT NULL,
  fechaNac date NOT NULL,
  tipo char(1) NOT NULL CHECK (tipo IN ('E','A','C','S')),
  nroRol varchar(15) NOT NULL REFERENCES rol(nro) ON UPDATE CASCADE ON DELETE RESTRICT,
  idEmp integer REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idUsuario),
  FOREIGN KEY (idEmp,nroRol) REFERENCES rol(idEmp,nro) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT ck_usuario_tipo_tenant CHECK ((tipo='S' AND idEmp IS NULL) OR (tipo<>'S' AND idEmp IS NOT NULL))
);
CREATE UNIQUE INDEX uq_usuario_correo_tenant ON usuario(COALESCE(idEmp,0),lower(btrim(correo)));
CREATE TABLE bitacora (
  id bigserial PRIMARY KEY,
  usuario_id varchar REFERENCES usuario(idUsuario) ON DELETE SET NULL,
  accion varchar(150) NOT NULL,
  ip inet,
  detalles jsonb,
  fecha timestamptz NOT NULL DEFAULT now(),
  idEmp integer REFERENCES empresa(idEmp),
  FOREIGN KEY (idEmp,usuario_id) REFERENCES usuario(idEmp,idUsuario)
);
CREATE TABLE recuperacion_contrasena (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  usuario_id varchar NOT NULL REFERENCES usuario(idUsuario),
  token_digest varchar(64) NOT NULL UNIQUE CHECK (token_digest ~ '^[0-9a-f]{64}$'),
  creada_en timestamptz NOT NULL DEFAULT now(),
  expira_en timestamptz NOT NULL,
  utilizada_en timestamptz,
  idEmp integer REFERENCES empresa(idEmp), -- NULL exclusivo de recuperacion administrador SaaS
  CHECK (expira_en > creada_en),
  CHECK (utilizada_en IS NULL OR utilizada_en >= creada_en),
  FOREIGN KEY (idEmp,usuario_id) REFERENCES usuario(idEmp,idUsuario) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX ix_recuperacion_usuario ON recuperacion_contrasena(idEmp,usuario_id);
CREATE INDEX ix_recuperacion_expira ON recuperacion_contrasena(expira_en);
CREATE TABLE admin (
  idUsuario varchar PRIMARY KEY,
  cod_adm varchar(10) NOT NULL,
  principal boolean NOT NULL DEFAULT false,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  FOREIGN KEY (idEmp,idUsuario) REFERENCES usuario(idEmp,idUsuario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE UNIQUE INDEX uq_admin_principal ON admin(idEmp) WHERE principal;

-- =================== SUCURSALES / EMPLEADOS ===================
CREATE TABLE ciudad (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(50) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,id)
);
CREATE TABLE sucursal (
  nro integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(50) NOT NULL,
  direccion varchar(100) NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo')),
  idCiud smallint NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,nro),
  FOREIGN KEY (idEmp,idCiud) REFERENCES ciudad(idEmp,id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE empleado (
  idUsuario varchar PRIMARY KEY,
  cod_emp varchar(10) NOT NULL,
  cargo varchar(50) NOT NULL,
  nroSuc integer NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idUsuario),
  FOREIGN KEY (idEmp,idUsuario) REFERENCES usuario(idEmp,idUsuario) ON UPDATE CASCADE ON DELETE CASCADE,
  FOREIGN KEY (idEmp,nroSuc) REFERENCES sucursal(idEmp,nro)
);
CREATE TABLE cliente (
  idUsuario varchar PRIMARY KEY,
  cod_cl varchar(10) NOT NULL,
  estado varchar(15) NOT NULL DEFAULT 'frecuente' CHECK (estado IN ('frecuente','casual','inactivo')),
  proporciones jsonb,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idUsuario),
  FOREIGN KEY (idEmp,idUsuario) REFERENCES usuario(idEmp,idUsuario) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE horario_trab (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno varchar(20) CHECK (turno IN ('manana','tarde','noche')),
  horaEntrada time NOT NULL,
  horaSalida time NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,id)
);
CREATE TABLE horario_emp (
  idUsuario varchar NOT NULL,
  idHorario smallint NOT NULL,
  dias varchar(100) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (idUsuario,idHorario),
  FOREIGN KEY (idEmp,idUsuario) REFERENCES empleado(idEmp,idUsuario) ON UPDATE CASCADE ON DELETE CASCADE,
  FOREIGN KEY (idEmp,idHorario) REFERENCES horario_trab(idEmp,id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE horario_atencion (
  idAten smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  horaIni time NOT NULL,
  horaFin time NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idAten)
);
CREATE TABLE horario_suc (
  idAten smallint NOT NULL,
  nroSuc integer NOT NULL,
  dias varchar(100) NOT NULL DEFAULT 'Lunes,Martes,Miercoles,Jueves,Viernes,Sabado,Domingo',
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (idAten,nroSuc),
  FOREIGN KEY (idEmp,idAten) REFERENCES horario_atencion(idEmp,idAten) ON UPDATE CASCADE ON DELETE CASCADE,
  FOREIGN KEY (idEmp,nroSuc) REFERENCES sucursal(idEmp,nro) ON UPDATE CASCADE ON DELETE CASCADE
);

-- =================== CATALOGO ===================
CREATE TABLE talla (
  idTalla smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(8) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idTalla)
);
CREATE TABLE color (
  idColor smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(20) NOT NULL,
  hex varchar(20) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idColor)
);
CREATE TABLE promocion (
  idPromo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  descripcion varchar(300),
  tipoDescuento varchar(30) NOT NULL CHECK (tipoDescuento IN ('porcentaje','montoFijo')),
  valorDescuento numeric(10,2) NOT NULL CHECK (valorDescuento > 0),
  fechaIni date NOT NULL,
  fechaFin date NOT NULL,
  estado varchar(20) NOT NULL CHECK (estado IN ('activo','inactivo')),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idPromo),
  CHECK (fechaFin >= fechaIni)
);
CREATE TABLE categoria (
  idCat integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(30) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idCat)
);
CREATE TABLE marca (
  idMarca integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(30) NOT NULL,
  estado varchar(20) NOT NULL CHECK (estado IN ('activo','inactivo')),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idMarca)
);
CREATE TABLE coleccion (
  idCol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion varchar(150) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idCol)
);
CREATE TABLE temporada (
  idTemp integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  fechaIni date NOT NULL,
  fechaFin date NOT NULL,
  estado varchar(20) NOT NULL CHECK (estado IN ('activo','inactivo')),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idTemp),
  CHECK (fechaFin >= fechaIni)
);
CREATE TABLE tempColeccion (
  idTemp integer NOT NULL,
  idCol integer NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (idTemp,idCol),
  FOREIGN KEY (idEmp,idTemp) REFERENCES temporada(idEmp,idTemp) ON UPDATE CASCADE ON DELETE CASCADE,
  FOREIGN KEY (idEmp,idCol) REFERENCES coleccion(idEmp,idCol) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE proveedor (
  idProv integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  correo varchar(150) NOT NULL,
  direccion varchar(150) NOT NULL,
  telefono varchar(20) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idProv)
);
CREATE TABLE producto (
  idProd varchar(50) PRIMARY KEY,
  descripcion varchar(100) NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo')),
  idPromo integer,
  idCat integer NOT NULL,
  idMarca integer NOT NULL,
  idCol integer NOT NULL,
  idProv integer NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idProd),
  FOREIGN KEY (idEmp,idPromo) REFERENCES promocion(idEmp,idPromo),
  FOREIGN KEY (idEmp,idCat) REFERENCES categoria(idEmp,idCat),
  FOREIGN KEY (idEmp,idMarca) REFERENCES marca(idEmp,idMarca),
  FOREIGN KEY (idEmp,idCol) REFERENCES coleccion(idEmp,idCol),
  FOREIGN KEY (idEmp,idProv) REFERENCES proveedor(idEmp,idProv)
);
CREATE TABLE varianteProd (
  idVariante varchar(15) PRIMARY KEY,
  sku varchar(30) NOT NULL,
  precio numeric(10,2) NOT NULL CHECK (precio > 0),
  estado varchar(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo')),
  img varchar(255),
  idTalla smallint NOT NULL,
  idProd varchar(50) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idVariante),
  UNIQUE (idEmp,sku),
  UNIQUE (idEmp,idProd,idVariante),
  FOREIGN KEY (idEmp,idTalla) REFERENCES talla(idEmp,idTalla),
  FOREIGN KEY (idEmp,idProd) REFERENCES producto(idEmp,idProd)
);
CREATE TABLE varianteColors (
  idVar varchar(15) NOT NULL,
  idColor smallint NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (idVar,idColor),
  FOREIGN KEY (idEmp,idVar) REFERENCES varianteProd(idEmp,idVariante) ON DELETE CASCADE,
  FOREIGN KEY (idEmp,idColor) REFERENCES color(idEmp,idColor)
);

-- Politicas generales: empresa.diasPlazoDevolucion/porcentajeDevolucion/condicionesDevolucion.
-- Cada empresa configura excepciones POR PRODUCTO. idvar puede ser NULL.
-- UNIQUE(idEmp,idprod) conserva una politica por producto; si se indica idvar,
-- la variante debe pertenecer al MISMO producto y tenant.
CREATE TABLE politica_devolucion (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idprod varchar(50) NOT NULL,
  idvar varchar(15),
  dias integer NOT NULL CHECK (dias > 0),
  porcentaje numeric(5,2) NOT NULL CHECK (porcentaje > 0 AND porcentaje <= 100),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idprod),
  FOREIGN KEY (idEmp,idprod) REFERENCES producto(idEmp,idProd) ON DELETE RESTRICT,
  FOREIGN KEY (idEmp,idprod,idvar) REFERENCES varianteProd(idEmp,idProd,idVariante) ON DELETE RESTRICT
);

-- =================== INVENTARIO Y COMERCIO ===================
CREATE TABLE inventario (
  nroInv integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stock integer NOT NULL CHECK (stock >= 0),
  cantDisp integer NOT NULL CHECK (cantDisp >= 0 AND cantDisp <= stock),
  nroSuc integer NOT NULL,
  idVar varchar(15) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,nroInv),
  UNIQUE (idEmp,nroSuc,idVar),
  FOREIGN KEY (idEmp,nroSuc) REFERENCES sucursal(idEmp,nro),
  FOREIGN KEY (idEmp,idVar) REFERENCES varianteProd(idEmp,idVariante)
);
CREATE TABLE movimiento_inv (
  idMov integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipoMov varchar(20) NOT NULL CHECK (tipoMov IN ('entrada','salida','ajuste')),
  cantidad integer NOT NULL CHECK (cantidad > 0),
  fecha date NOT NULL DEFAULT current_date,
  motivo varchar(255) NOT NULL,
  nroInv integer NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  FOREIGN KEY (idEmp,nroInv) REFERENCES inventario(idEmp,nroInv)
);
CREATE TABLE carrito (
  idCarrito integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fechahora timestamp NOT NULL DEFAULT now(),
  idUsuarioCl varchar NOT NULL,
  estado varchar(20) NOT NULL CHECK (estado IN ('activo','convertido','abandonado')),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idCarrito),
  FOREIGN KEY (idEmp,idUsuarioCl) REFERENCES cliente(idEmp,idUsuario)
);
CREATE UNIQUE INDEX uq_carrito_activo_cliente ON carrito(idEmp,idUsuarioCl) WHERE estado='activo';
CREATE TABLE detalleCarro (
  idCarrito integer NOT NULL,
  idDetalleCarro integer NOT NULL,
  idVar varchar(15) NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (idCarrito,idDetalleCarro),
  FOREIGN KEY (idEmp,idCarrito) REFERENCES carrito(idEmp,idCarrito) ON DELETE CASCADE,
  FOREIGN KEY (idEmp,idVar) REFERENCES varianteProd(idEmp,idVariante),
  UNIQUE (idEmp,idCarrito,idVar)
);
CREATE TABLE reserva (
  nroReserva integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fechaReserva date NOT NULL,
  horaAtencion time NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','confirmada','atendida','cancelada','vencida')),
  nroSuc integer NOT NULL,
  idUsuarioCl varchar NOT NULL,
  idOperacion uuid,
  origen varchar(20) NOT NULL DEFAULT 'servidor' CHECK (origen IN ('servidor','pwa','movil')),
  fechaSync timestamptz,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,nroReserva),
  UNIQUE (idEmp,idOperacion),
  FOREIGN KEY (idEmp,nroSuc) REFERENCES sucursal(idEmp,nro),
  FOREIGN KEY (idEmp,idUsuarioCl) REFERENCES cliente(idEmp,idUsuario)
);
CREATE TABLE detalleReserva (
  nroReserva integer NOT NULL,
  idDetalleRes integer NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  idVar varchar(15) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (nroReserva,idDetalleRes),
  FOREIGN KEY (idEmp,nroReserva) REFERENCES reserva(idEmp,nroReserva) ON DELETE CASCADE,
  FOREIGN KEY (idEmp,idVar) REFERENCES varianteProd(idEmp,idVariante),
  UNIQUE (idEmp,nroReserva,idVar)
);
CREATE TABLE venta (
  nroVenta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nit varchar(30),
  fechaHora timestamp NOT NULL DEFAULT now(),
  total numeric(10,2) NOT NULL CHECK (total >= 0),
  desc_aplicado numeric(10,2) NOT NULL DEFAULT 0 CHECK (desc_aplicado >= 0),
  estado varchar(30) NOT NULL CHECK (estado IN ('registrada','anulada')),
  idUsuarioCl varchar, -- permitido NULL para venta offline de contado
  idUsuarioEmp varchar,
  nroSuc integer NOT NULL,
  idCarrito integer,
  nroReserva integer,
  idOperacion uuid,
  origen varchar(20) NOT NULL DEFAULT 'servidor' CHECK (origen IN ('servidor','pwa','movil')),
  fechaSync timestamptz,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,nroVenta),
  UNIQUE (idEmp,idOperacion),
  FOREIGN KEY (idEmp,idUsuarioCl) REFERENCES cliente(idEmp,idUsuario),
  FOREIGN KEY (idEmp,idUsuarioEmp) REFERENCES empleado(idEmp,idUsuario),
  FOREIGN KEY (idEmp,nroSuc) REFERENCES sucursal(idEmp,nro),
  FOREIGN KEY (idEmp,idCarrito) REFERENCES carrito(idEmp,idCarrito),
  FOREIGN KEY (idEmp,nroReserva) REFERENCES reserva(idEmp,nroReserva)
);
CREATE TABLE detalleVenta (
  nroVenta integer NOT NULL,
  idDetalleVenta integer NOT NULL,
  cantidad integer NOT NULL DEFAULT 1 CHECK (cantidad > 0),
  precioUnitario numeric(10,2) NOT NULL CHECK (precioUnitario > 0),
  -- Snapshot de política al momento de vender; no cambia retroactivamente.
  diasDevolucionAplicado integer CHECK (diasDevolucionAplicado >= 0),
  porcentajeDevolucionAplicado numeric(5,2)
      CHECK (porcentajeDevolucionAplicado > 0 AND porcentajeDevolucionAplicado <= 100),
  condicionesDevolucionAplicadas text,
  idVar varchar(15) NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (nroVenta,idDetalleVenta),
  UNIQUE (idEmp,nroVenta,idDetalleVenta),
  FOREIGN KEY (idEmp,nroVenta) REFERENCES venta(idEmp,nroVenta) ON DELETE CASCADE,
  FOREIGN KEY (idEmp,idVar) REFERENCES varianteProd(idEmp,idVariante)
);
CREATE TABLE devolucion (
  nroDev integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fechaHora timestamp NOT NULL DEFAULT now(),
  monto numeric(10,2) NOT NULL CHECK (monto >= 0),
  estado varchar(30) NOT NULL CHECK (estado IN ('pendiente','rechazada','aprobada')),
  nroVenta integer NOT NULL,
  motivo varchar(255),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,nroDev),
  UNIQUE (idEmp,nroDev,nroVenta),
  FOREIGN KEY (idEmp,nroVenta) REFERENCES venta(idEmp,nroVenta)
);
CREATE TABLE detalleDev (
  nroDev integer NOT NULL,
  idDetalleDev integer NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  nroVenta integer NOT NULL,
  idDetalleVenta integer NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (nroDev,idDetalleDev),
  FOREIGN KEY (idEmp,nroDev,nroVenta) REFERENCES devolucion(idEmp,nroDev,nroVenta) ON DELETE CASCADE,
  FOREIGN KEY (idEmp,nroVenta,idDetalleVenta) REFERENCES detalleVenta(idEmp,nroVenta,idDetalleVenta),
  UNIQUE (idEmp,nroDev,nroVenta,idDetalleVenta)
);
CREATE TABLE pago (
  idPago integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  metodo varchar(30) NOT NULL CHECK (metodo IN ('tarjeta','QR','transferencia','efectivo')),
  monto numeric(10,2) NOT NULL CHECK (monto >= 0),
  estado varchar(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','aprobado','rechazado')),
  fechaHora timestamp NOT NULL DEFAULT now(),
  referencia varchar(100),
  nroVenta integer NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,idPago),
  UNIQUE (idEmp,idPago,nroVenta),
  FOREIGN KEY (idEmp,nroVenta) REFERENCES venta(idEmp,nroVenta)
);
CREATE TABLE reembolso (
  idReembolso integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  metodo varchar(30) NOT NULL CHECK (metodo IN ('tarjeta','QR','transferencia','efectivo')),
  monto numeric(10,2) NOT NULL CHECK (monto >= 0),
  fechaHora timestamp NOT NULL DEFAULT now(),
  estado varchar(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','aprobado','rechazado')),
  idPago integer NOT NULL,
  nroDev integer NOT NULL,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  FOREIGN KEY (idEmp,idPago) REFERENCES pago(idEmp,idPago),
  FOREIGN KEY (idEmp,nroDev) REFERENCES devolucion(idEmp,nroDev)
);
CREATE UNIQUE INDEX uq_reembolso_emp_dev_vigente ON reembolso(idEmp,nroDev)
 WHERE estado IN ('pendiente','aprobado');

-- =================== CAMBIOS DE PRENDAS ===================
CREATE TABLE cambio (
  nroCambio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fechaHora timestamp NOT NULL DEFAULT now(),
  estado varchar(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','aprobado','rechazado')),
  motivo varchar(255),
  difMonto numeric(10,2) NOT NULL DEFAULT 0,
  nroVenta integer NOT NULL,
  nroSuc integer NOT NULL,
  idUsuarioEmp varchar,
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  UNIQUE (idEmp,nroCambio),
  UNIQUE (idEmp,nroCambio,nroVenta),
  FOREIGN KEY (idEmp,nroVenta) REFERENCES venta(idEmp,nroVenta),
  FOREIGN KEY (idEmp,nroSuc) REFERENCES sucursal(idEmp,nro),
  FOREIGN KEY (idEmp,idUsuarioEmp) REFERENCES empleado(idEmp,idUsuario)
);
CREATE TABLE detalleCambio (
  nroCambio integer NOT NULL,
  idDetalleCambio integer NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  nroVenta integer NOT NULL,
  idDetalleVenta integer NOT NULL,
  idVarNueva varchar(15) NOT NULL,
  precioNuevo numeric(10,2) NOT NULL CHECK (precioNuevo > 0),
  idEmp integer NOT NULL REFERENCES empresa(idEmp),
  PRIMARY KEY (nroCambio,idDetalleCambio),
  FOREIGN KEY (idEmp,nroCambio,nroVenta) REFERENCES cambio(idEmp,nroCambio,nroVenta) ON DELETE CASCADE,
  FOREIGN KEY (idEmp,nroVenta,idDetalleVenta) REFERENCES detalleVenta(idEmp,nroVenta,idDetalleVenta),
  FOREIGN KEY (idEmp,idVarNueva) REFERENCES varianteProd(idEmp,idVariante)
);

