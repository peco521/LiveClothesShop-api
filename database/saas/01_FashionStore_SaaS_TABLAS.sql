  codigoMotivo varchar(40),
  detalleMotivo text,
  payload jsonb NOT NULL,
  nroVenta integer,
  nroReserva integer,
  resueltaPor varchar,
  fechaResolucion timestamptz,
  PRIMARY KEY (idEmp,idOperacion),
  FOREIGN KEY (idEmp,nroSuc) REFERENCES sucursal(idEmp,nro),
  FOREIGN KEY (idEmp,idUsuario) REFERENCES usuario(idEmp,idUsuario),
  FOREIGN KEY (idEmp,nroVenta) REFERENCES venta(idEmp,nroVenta),
  FOREIGN KEY (idEmp,nroReserva) REFERENCES reserva(idEmp,nroReserva),
  FOREIGN KEY (idEmp,resueltaPor) REFERENCES usuario(idEmp,idUsuario)
